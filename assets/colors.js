KI.findColorByName = function (name) {
  if (!name) return null;
  var n = String(name).trim();
  for (var i = 0; i < KI.PALETTE.length; i++) {
    if (KI.PALETTE[i].name === n) return KI.PALETTE[i];
  }
  return null;
};

/* API が使えないときのローカル辞書マッチ。
 * 入力文に含まれるキーワードの数でスコアし、最高得点の色を返す。
 * 1つも当たらないときは入力文字列のハッシュで安定的に1色選ぶ。 */
KI.matchColor = function (text) {
  var input = String(text || '');
  var best = null;
  var bestScore = 0;
  for (var i = 0; i < KI.PALETTE.length; i++) {
    var c = KI.PALETTE[i];
    var score = 0;
    for (var k = 0; k < c.keywords.length; k++) {
      if (input.indexOf(c.keywords[k]) !== -1) score++;
    }
    if (score > bestScore) { bestScore = score; best = c; }
  }
  if (best) return best;
  var h = 0;
  for (var j = 0; j < input.length; j++) h = (h * 31 + input.charCodeAt(j)) >>> 0;
  return KI.PALETTE[h % KI.PALETTE.length];
};
