/* 結果の中身を組み立てる。すべて固定文なので、外に問い合わせるものは何もない。 */
KI.resultFor = function (version, color) {
  return {
    color: color,
    message: 'きょうは' + color.name + 'のちからをかりてみましょう。',
    howto: version.suggestion(color) + color.name + 'は' + color.meaning + color.closing
  };
};
