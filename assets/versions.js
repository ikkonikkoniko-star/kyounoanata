/* 色ごとに安定してアイテムを選ぶ（同じ色なら毎回同じ提案になる） */
function pick(list, hex, offset) {
  var c = KI.hexToRgb(hex);
  var seed = c.r * 3 + c.g * 5 + c.b * 7 + offset * 11;
  return list[seed % list.length];
}

